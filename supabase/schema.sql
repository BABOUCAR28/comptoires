-- À exécuter UNE FOIS dans Supabase : Dashboard > SQL Editor > New query > coller > Run.
create table if not exists products (
  id bigint generated by default as identity primary key,
  cat text not null check (cat in ('sucres','sales','fatayas','jus')),
  name text not null,
  descr text,
  price integer check (price >= 0),
  unit text default 'pièce',
  minq integer check (minq >= 1),
  delay text,
  garniture text,
  img text,
  published boolean not null default true
);
create table if not exists orders (
  id bigint generated by default as identity primary key,
  created timestamptz not null default now(),
  kind text not null check (kind in ('commande','evenement')),
  status text not null default 'recue' check (status in ('recue','en_cours','confirmee','refusee')),
  data jsonb not null
);
create table if not exists settings (k text primary key, v text);

-- SÉCURITÉ : RLS activé SANS aucune règle = personne (clé publique "anon" incluse) ne peut lire ni écrire.
-- Seul le serveur du site, avec la clé secrète "service", y accède.
alter table products enable row level security;
alter table orders   enable row level security;
alter table settings enable row level security;

-- Dossier de photos (lecture publique des images, écriture réservée au serveur).
insert into storage.buckets (id, name, public) values ('uploads', 'uploads', true) on conflict (id) do nothing;

-- Utilisé uniquement par le script de migration (remet les compteurs d'identifiants à jour).
create or replace function fix_sequences() returns void language sql as $$
  select setval(pg_get_serial_sequence('products','id'), coalesce((select max(id) from products),0)+1, false);
  select setval(pg_get_serial_sequence('orders','id'),   coalesce((select max(id) from orders),0)+1, false);
$$;
revoke all on function fix_sequences() from public, anon, authenticated;
